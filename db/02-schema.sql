CREATE TABLE users
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT users_name_uk UNIQUE (name)
);

CREATE TABLE meeting
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    description TEXT
);

-- Append-only event log: the calendar of a user is the projection of its events (applied by id)
CREATE TABLE event
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id BIGINT      NOT NULL REFERENCES users (id),
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    event_type VARCHAR(32) NOT NULL,
    meeting_id BIGINT REFERENCES meeting (id),
    start_time TIMESTAMP   NOT NULL,
    end_time   TIMESTAMP   NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT event_type_ck
        CHECK (event_type IN ('MARKED_FREE', 'MARKED_BUSY', 'MEETING_BOOKED')),
    -- meeting_id is set only for MEETING_BOOKED
    CONSTRAINT event_meeting_id_ck
        CHECK ((event_type = 'MEETING_BOOKED') = (meeting_id IS NOT NULL)),
    -- [start_time, end_time): start is included, end is not
    CONSTRAINT event_time_range_ck
        CHECK (end_time > start_time),
    -- time quantum is 15 min
    CONSTRAINT event_start_time_quantum_ck
        CHECK (extract(MINUTE FROM start_time)::INT % 15 = 0
            AND date_trunc('minute', start_time) = start_time),
    CONSTRAINT event_end_time_quantum_ck
        CHECK (extract(MINUTE FROM end_time)::INT % 15 = 0
            AND date_trunc('minute', end_time) = end_time)
);

-- Calendar App: events of a user within a time frame
CREATE INDEX event_user_id_start_time_idx ON event (user_id, start_time);

-- Events (participants' calendars) of a meeting
CREATE INDEX event_meeting_id_idx ON event (meeting_id);
